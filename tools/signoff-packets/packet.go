// Packet is one review workbook.
type Packet struct {
	// Name is the file name (without .xlsx) and the -only value.
	Name  string
	Title string
	// Item is the #512 row the packet serves.
	Item string
	// Sources are the fixtures it is made from, relative to the repository root.
	Sources []string
	// Checks say what the reviewer confirms, one line each.
	Checks []string
	// Build reads the sources and returns the sheets after the cover.
	Build func(root string) ([]*Table, error)
}

// Meta is what the cover prints besides the packet itself.
type Meta struct {
	Commit string
	Date   string
}

// Table is one sheet: a header row and data rows. About says on the cover what the sheet holds.
type Table struct {
	Name   string
	About  string
	Header []string
	Rows   [][]xlsx.Cell
}

func newTable(name, about string, header ...string) *Table {
	return &Table{Name: name, About: about, Header: header}
}

func (t *Table) add(cells ...xlsx.Cell) { t.Rows = append(t.Rows, cells) }

func (t *Table) sheet() xlsx.Sheet {
	rows := make([][]xlsx.Cell, 0, len(t.Rows)+1)
	head := make([]xlsx.Cell, len(t.Header))
	for i, h := range t.Header {
		head[i] = xlsx.Str(h)
	}
	rows = append(rows, head)
	rows = append(rows, t.Rows...)
	return xlsx.Sheet{Name: t.Name, Rows: rows}
}

// Generate builds the workbook of a packet: the cover, then the packet's sheets.
func Generate(p Packet, root string, meta Meta) ([]byte, []*Table, error) {
	tables, err := p.Build(root)
	if err != nil {
		return nil, nil, err
	}
	sheets := []xlsx.Sheet{cover(p, meta, tables)}
	for _, t := range tables {
		sheets = append(sheets, t.sheet())
	}
	book, err := xlsx.Write(sheets)
	return book, tables, err
}

// Sign-off fields on the cover, in order; the reviewer fills in the cell to the right of each.
var signOffFields = []string{"Reviewer name", "Date reviewed", "Result (accepted, accepted with comments, rejected)", "Comments"}

func cover(p Packet, meta Meta, tables []*Table) xlsx.Sheet {
	var rows [][]xlsx.Cell
	add := func(cells ...string) {
		row := make([]xlsx.Cell, len(cells))
		for i, c := range cells {
			row[i] = xlsx.Str(c)
		}
		rows = append(rows, row)
	}
	add("Depot sign-off packet", p.Title)
	add("Serves", p.Item)
	for i, s := range p.Sources {
		label := ""
		if i == 0 {
			label = "Source fixture"
		}
		add(label, s)
	}
	add("Git commit", meta.Commit)
	add("Generated on", meta.Date)
	add("Generated by", "go -C tools/signoff-packets run . -out <absolute dir> -only "+p.Name+" (from the repository root)")
	add()
	add("What to check")
	for i, c := range p.Checks {
		add(strconv.Itoa(i+1), c)
	}
	add()
	add("Sheets")
	for _, t := range tables {
		add(t.Name, fmt.Sprintf("%s (%d rows)", t.About, len(t.Rows)))
	}
	add()
	add("Sign-off")
	for _, f := range signOffFields {
		add(f, "")
	}
	return xlsx.Sheet{Name: "Cover", Rows: rows}
}

// Cell helpers. Numbers keep the decimal text they are given, so nothing is lost to floating point.

func str(s string) xlsx.Cell { return xlsx.Str(s) }

// num is a number cell from decimal text; empty text is a blank cell. Text that is not a decimal stays text.
func num(s string) xlsx.Cell {
	if s == "" {
		return xlsx.Cell{}
	}
	if _, err := decimal.NewFromString(s); err != nil {
		return xlsx.Str(s)
	}
	return xlsx.Num(s)
}

func money(d decimal.Decimal) xlsx.Cell { return xlsx.Num(d.StringFixed(2)) }

func integer(n int) xlsx.Cell { return xlsx.Num(strconv.Itoa(n)) }

func yesNo(b bool) xlsx.Cell {
	if b {
		return xlsx.Str("yes")
	}
	return xlsx.Str("no")
}

// dec parses decimal text from a fixture; a fixture is trusted input, so a bad value is a build error the caller reports.
func dec(s string) (decimal.Decimal, error) {
	if s == "" {
		return decimal.Zero, nil
	}
	return decimal.NewFromString(s)
}

func readJSON(root, rel string, v any) error {
	raw, err := os.ReadFile(filepath.Join(root, rel))
	if err != nil {
		return err
	}
	if err := json.Unmarshal(raw, v); err != nil {
		return fmt.Errorf("%s: %w", rel, err)
	}
	return nil
}

// readCSV returns the header and the records of a CSV fixture.
func readCSV(root, rel string) ([]string, [][]string, error) {
	f, err := os.Open(filepath.Join(root, rel))
	if err != nil {
		return nil, nil, err
	}
	defer func() { _ = f.Close() }()
	all, err := csv.NewReader(f).ReadAll()
	if err != nil {
		return nil, nil, fmt.Errorf("%s: %w", rel, err)
	}
	if len(all) == 0 {
		return nil, nil, fmt.Errorf("%s is empty", rel)
	}
	return all[0], all[1:], nil
}

// columns maps a CSV header to column positions and fails on a missing column.
func columns(rel string, header []string, want ...string) (map[string]int, error) {
	at := map[string]int{}
	for i, h := range header {
		at[h] = i
	}
	for _, w := range want {
		if _, ok := at[w]; !ok {
			return nil, fmt.Errorf("%s has no column %s", rel, w)
		}
	}
	return at, nil
}
