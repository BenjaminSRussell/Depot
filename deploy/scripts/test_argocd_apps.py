def selector_names(selector):
    """The app.kubernetes.io/name values a podSelector matches (matchLabels or an In expression), or None for other selectors."""
    labels = selector.get("matchLabels") or {}
    exprs = selector.get("matchExpressions") or []
    if set(labels) == {"app.kubernetes.io/name"} and not exprs:
        return {labels["app.kubernetes.io/name"]}
    if not labels and len(exprs) == 1 and exprs[0]["key"] == "app.kubernetes.io/name" and exprs[0]["operator"] == "In":
        return set(exprs[0]["values"])
    return None


def pod_template(doc):
    spec = doc.get("spec") or {}
    if not isinstance(spec, dict):
        return None
    if doc["kind"] == "CronJob":
        return ((spec.get("jobTemplate") or {}).get("spec") or {}).get("template")
    if doc["kind"] in ("Deployment", "StatefulSet", "DaemonSet", "Job"):
        return spec.get("template")
    return None


def named_ports(docs):
    """{port name: container port} over every pod the chart renders (a NetworkPolicy may name a port instead of numbering it)."""
    return {p["name"]: p["containerPort"] for d in docs if pod_template(d)
            for c in (pod_template(d).get("spec") or {}).get("containers") or [] for p in c.get("ports") or [] if p.get("name")}


def port_covers(entry, number, names):
    """Whether one NetworkPolicy port entry admits TCP port `number`: no port at all, the number, a range up to endPort, or a
    named port that resolves to it."""
    if entry.get("protocol", "TCP") != "TCP":
        return False
    port = entry.get("port")
    if port is None:
        return True
    if isinstance(port, str):
        port = names.get(port)
        return port == number
    return port == number or (entry.get("endPort") is not None and port <= number <= entry["endPort"])


def rule_ports(rule):
    return {p["port"] for p in rule.get("ports") or []}


def exact_ports(rule):
    """The rule's ports when every entry is a plain TCP number (no name, no range), else None."""
    entries = rule.get("ports") or []
    if not entries or any(e.get("protocol", "TCP") != "TCP" or not isinstance(e.get("port"), int) or "endPort" in e for e in entries):
        return None
    return {e["port"] for e in entries}


def ingress_policy_problems(docs, release, namespace, expected):
    """Why the rendered chart docs do not carry D1's default-deny ingress policy (ADR-0006 rule 6); empty when they do.

    expected is the chart's generated ingressPolicy (deploy/scripts/gen_networkpolicies.py). The policy <release>-ingress
    must select every pod the chart renders but the migration Job's (D28), deny ingress by default, admit the API port only from the listed Gateways'
    Envoy pods and exactly the generated peers (plus the ingress controller for hello-ledger's smoke Ingress), and the
    metrics ports only from Prometheus, every port a plain TCP number. No other NetworkPolicy of the chart may admit the API
    or metrics ports, by number, name or range (policies are additive, so one broad rule would undo the default deny).
    """
    problems = []
    policies = [d for d in docs if d["kind"] == "NetworkPolicy"]
    mine = [p for p in policies if p["metadata"]["name"] == f"{release}-ingress"]
    if len(mine) != 1:
        return [f"no NetworkPolicy {release}-ingress (run python3 deploy/scripts/gen_networkpolicies.py)"]
    spec = mine[0]["spec"]
    if spec.get("policyTypes") != ["Ingress"]:
        problems.append(f"policyTypes {spec.get('policyTypes')}, want [Ingress]")
    selected = selector_names(spec["podSelector"])
    if not selected:
        problems.append(f"podSelector {spec['podSelector']} does not select by app.kubernetes.io/name")
        selected = set()
    for d in docs:
        pod = pod_template(d)
        if pod is None:
            continue
        labels = pod.get("metadata", {}).get("labels") or {}
        name = labels.get("app.kubernetes.io/name")
        if labels.get("app.kubernetes.io/component") == "migrate":
            # The owner-role migration Job (D28) opens no port: it is left to the namespace default-deny, never selected
            # here (deploy/scripts/test_migrate_jobs.py checks its labels, ports and that no policy selects it).
            if name in selected:
                problems.append(f"{d['kind']} {d['metadata']['name']}: the migration Job's pod is selected by {release}-ingress")
            continue
        if name not in selected:
            problems.append(f"{d['kind']} {d['metadata']['name']} (app.kubernetes.io/name {name}) is not selected")
    api, metrics, names = expected["apiPort"], set(expected["metricsPorts"]), named_ports(docs)
    ingress_on = any(d["kind"] == "Ingress" for d in docs)
    controller = expected.get("ingressController")
    controller_peer = controller and {
        "namespaceSelector": {"matchLabels": {"kubernetes.io/metadata.name": controller["namespace"]}},
        "podSelector": {"matchLabels": controller["podLabels"]}}
    api_rules, metrics_rules = [], []
    for rule in spec.get("ingress") or []:
        ports, sources = exact_ports(rule), rule.get("from")
        if ports is None or not sources:
            problems.append(f"rule {rule} admits every source, or names its ports by name or range")
            continue
        if any(not f.get("podSelector") or "ipBlock" in f for f in sources):
            problems.append(f"rule {rule} admits a whole namespace or an address block")
        if ports == metrics and sources == [PROMETHEUS_PEER]:
            metrics_rules.append(rule)
        elif ports == {api}:
            api_rules.append(sources)
        else:
            problems.append(f"unexpected rule {rule}")
    # Every API-port rule is the gateway-and-peers rule or, for hello-ledger with its Ingress on, the ingress controller.
    want_rules = (1 if expected["gateway"]["names"] or expected["peers"] else 0) + (1 if controller and ingress_on else 0)
    if len(api_rules) != want_rules:
        problems.append(f"{len(api_rules)} rules admit the API port, want {want_rules}")
    main_rules = [s for s in api_rules if s != [controller_peer]]
    if controller and ingress_on and [controller_peer] not in api_rules:
        problems.append(f"no API rule for the ingress controller {controller}")
    sources = main_rules[0] if main_rules else []
    gateways = [f for f in sources if f.get("namespaceSelector", {}).get("matchLabels") == GATEWAY_PODS]
    got_peers = {(f.get("namespaceSelector", {}).get("matchLabels", {}).get("kubernetes.io/metadata.name", namespace),
                  frozenset(selector_names(f["podSelector"]) or ())) for f in sources if f not in gateways}
    want_peers = {(p.get("namespace", namespace), frozenset(p["podNames"])) for p in expected["peers"]}
    if got_peers != want_peers:
        problems.append(f"API peers {sorted(got_peers)}, want the generated {sorted(want_peers)}")
    for f in sources:
        if f not in gateways and set(f) - {"namespaceSelector", "podSelector"}:
            problems.append(f"peer {f} carries more than a namespace and a pod selector")
        if f not in gateways and "namespaceSelector" in f and set(f["namespaceSelector"]) != {"matchLabels"}:
            problems.append(f"peer {f} selects namespaces by more than their name")
    if expected["gateway"]["names"]:
        want = {"gateway.envoyproxy.io/owning-gateway-namespace": [expected["gateway"]["gatewaysNamespace"]],
                "gateway.envoyproxy.io/owning-gateway-name": expected["gateway"]["names"]}
        got = [{e["key"]: e["values"] for e in g["podSelector"].get("matchExpressions") or [] if e["operator"] == "In"}
               for g in gateways]
        if got != [want] or any(g["podSelector"].get("matchLabels") for g in gateways):
            problems.append(f"gateway peers {got}, want {want}")
    elif gateways:
        problems.append(f"gateway peers {gateways}, want none")
    if metrics and len(metrics_rules) != 1:
        problems.append(f"metrics ports {sorted(metrics)} are not admitted to Prometheus alone")
    if not metrics and metrics_rules:
        problems.append("a metrics rule without metrics ports")
    guarded = {api} | metrics | {ADMIN_PORT_DEFAULT}
    for other in policies:
        if other is mine[0] or "Ingress" not in other["spec"].get("policyTypes", ["Ingress"]):
            continue
        for rule in other["spec"].get("ingress") or []:
            entries = rule.get("ports") or [{}]
            opened = sorted(n for n in guarded if any(port_covers(e, n, names) for e in entries))
            if opened:
                problems.append(f"NetworkPolicy {other['metadata']['name']} also admits {opened}")
    return problems


