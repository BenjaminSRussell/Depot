        users, topics = {}, set()
        for _, _, files, _ in directory_sources(self.apps, "dev"):
            for f in files:
                for doc in load_docs(f):
                    if doc.get("kind") == "KafkaUser":
                        acls = doc["spec"].get("authorization", {}).get("acls") or []
