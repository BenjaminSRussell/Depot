def service_chart_sources(app):
    """The sources of app that are service charts in this repository (services/ or tools/)."""
    return [s for s in sources(app) if s.get("path", "").startswith(("services/", "tools/"))
            and (REPO / s["path"] / "Chart.yaml").is_file()]


def release_name(app, src):
    return src.get("helm", {}).get("releaseName", app["metadata"]["name"])


_RENDERED = {}


def render(app, src):
    """The chart's documents rendered with the Application's values (cached: several tests render every dev chart)."""
    key = json.dumps([app["metadata"]["name"], app["spec"]["destination"], src], sort_keys=True)
    if key not in _RENDERED:
        _RENDERED[key] = _render(app, src)
    return copy.deepcopy(_RENDERED[key])


def _render(app, src):
    helm = src.get("helm", {})
    cmd = ["helm", "template", helm.get("releaseName", app["metadata"]["name"]), str(REPO / src["path"]),
           "--namespace", app["spec"]["destination"]["namespace"]]
    for vf in helm.get("valueFiles", []):
        file = REPO / vf.partition("/")[2]
        if file.is_file():
            cmd += ["-f", str(file)]
    with tempfile.TemporaryDirectory() as tmp:
        if helm.get("valuesObject"):
            obj = Path(tmp) / "values.yaml"
            obj.write_text(yaml.safe_dump(helm["valuesObject"]))
            cmd += ["-f", str(obj)]
        for p in helm.get("parameters", []):
            cmd += ["--set-string" if p.get("forceString") else "--set", f"{p['name']}={p['value']}"]
        res = subprocess.run(cmd, capture_output=True, text=True, env={**os.environ, "HELM_NAMESPACE": ""})
    if res.returncode:
        raise AssertionError(f"helm template {src['path']} failed: {res.stderr.strip()}")
    return [d for d in yaml.safe_load_all(res.stdout) if d]


