#!/usr/bin/env python3
"""Generate the owner-role migration Job of every chart whose service has migrations (D28, ADR-0012 rule 3, B-09a).

    python3 deploy/scripts/gen_migrate_jobs.py           # write the generated files
    python3 deploy/scripts/gen_migrate_jobs.py --check   # exit 1 when a committed file differs from the generated one

A service has migrations when its directory (services/<dir> or tools/<dir>) holds migrations/*.sql; its chart is the one
chart under <dir>/charts. For each such chart this script writes:

- templates/migrate-job.yaml, identical in every chart: a Job that runs the service image's migrate command (Go
  `<binary> migrate` through dbx.HandleMigrateCommand, `node <entry> migrate` for the TypeScript services,
  `python -m <package>.migrate` for Python) with the owner role's database URL from migrateJob.ownerSecret, as
  DATABASE_URL and MIGRATE_DATABASE_URL. It is an Argo CD PreSync hook (and a Helm pre-install/pre-upgrade hook for a
  plain `helm install`), so a sync applies the schema before any Deployment of the release changes, and a failed
  migration fails the sync instead of rolling pods onto a schema they do not expect. Its pod is labelled
  `app.kubernetes.io/name: <chart>-migrate` and `app.kubernetes.io/component: migrate`, never the service's own name: the
  chart's Service would otherwise route requests to it, and the generated NetworkPolicies (gen_networkpolicies.py), which
  select and admit pods by that name, would give it the service's ingress and peer access. It opens no port, so the
  namespace default-deny refuses every connection to it; its egress is not restricted, and the Postgres NetworkPolicies
  admit migrate pods (deploy/postgres, deploy/envs/dev/apps/postgres.yaml).
  The template refuses to render when the serving pods would also migrate on start (the chart value named by
  migrateJob.servingMigrateOnStart is "true"): MIGRATE_ON_START=true is for a chart whose Job is disabled.
- the `migrateJob` block of the chart's values.yaml, between the >>> and <<< marker lines (before the ingressPolicy block):
  enabled, the container command and args for the service's language, the owner Secret (default `<chart>-db-owner`, key
  DATABASE_URL), backoffLimit, activeDeadlineSeconds, resources and the values path of the serving pods' MIGRATE_ON_START.
  Override per environment in deploy/envs/<env>/values or the Application's values.

deploy/scripts/test_migrate_jobs.py runs --check, fails when a service with migrations has no Job, and renders every chart
with helm to check the Job and that no serving container migrates on start.
"""

import argparse
import re
import sys
from pathlib import Path

import yaml

DEPLOY = Path(__file__).resolve().parents[1]
REPO = DEPLOY.parent
TEMPLATE_NAME = "migrate-job.yaml"
BEGIN = "# >>> migrateJob: generated by deploy/scripts/gen_migrate_jobs.py (D28, ADR-0012 rule 3); do not edit, run the script."
END = "# <<< migrateJob"
INGRESS_BEGIN = "# >>> ingressPolicy:"

# How the image runs its migrate command when it is not a Go binary (whose ENTRYPOINT is the service binary, so the
# command is the single argument "migrate"). Keyed by the service directory.
NON_GO = {
    # distroless nodejs: the entrypoint is node, the image's CMD is the script.
    "agents-ts": {"command": [], "args": ["dist/main.js", "migrate"]},
    # node:alpine: docker-entrypoint.sh runs the given command.
    "integration-hub-ts": {"command": [], "args": ["node", "src/main.ts", "migrate"]},
    "prediction-py": {"command": ["python", "-m", "prediction.migrate"], "args": []},
}
SERVING_VALUE = re.compile(r"name:\s*MIGRATE_ON_START\s*\n\s*value:\s*\{\{-?\s*\.Values\.([A-Za-z0-9_.]+)\s*\|\s*quote\s*-?\}\}")


def service_dirs():
    """Service and tool directories with migrations/*.sql, sorted."""
    out = []
    for base in ("services", "tools"):
        for d in sorted((REPO / base).iterdir()):
            if (d / "migrations").is_dir() and any((d / "migrations").glob("*.sql")):
                out.append(d)
    return out


def chart_of(service):
    charts = sorted(p.parent for p in (service / "charts").glob("*/Chart.yaml")) if (service / "charts").is_dir() else []
    if len(charts) != 1:
        raise SystemExit(f"{service.relative_to(REPO)}: has migrations but {len(charts)} charts; the migration Job needs exactly one")
    return charts[0]


def charts():
    """[(service dir, chart dir)] for every service with migrations."""
    return [(s, chart_of(s)) for s in service_dirs()]


def serving_value(chart):
    """The values path the serving pods' MIGRATE_ON_START comes from, "" when no template sets it."""
    paths = set()
    for tpl in sorted((chart / "templates").iterdir()):
        if tpl.is_file() and tpl.name != TEMPLATE_NAME:
            paths |= set(SERVING_VALUE.findall(tpl.read_text()))
    values = yaml.safe_load((chart / "values.yaml").read_text()) or {}
    for env_map in ("env", "config"):
        if isinstance(values.get(env_map), dict) and "MIGRATE_ON_START" in values[env_map]:
            paths.add(f"{env_map}.MIGRATE_ON_START")
    if len(paths) > 1:
        raise SystemExit(f"{chart.relative_to(REPO)}: MIGRATE_ON_START comes from several values {sorted(paths)}; teach serving_value()")
    return paths.pop() if paths else ""


def job_values(service, chart):
    name = yaml.safe_load((chart / "Chart.yaml").read_text())["name"]
    run = NON_GO.get(service.name)
    if run is None:
        if not (service / "go.mod").is_file():
            raise SystemExit(f"{service.relative_to(REPO)}: not a Go module and not in NON_GO; say how its image migrates")
        run = {"command": [], "args": ["migrate"]}
    return {
        "enabled": True,
        "command": run["command"],
        "args": run["args"],
        "ownerSecret": f"{name}-db-owner",
        "ownerSecretKey": "DATABASE_URL",
        "backoffLimit": 2,
        "activeDeadlineSeconds": 600,
        "resources": {"requests": {"cpu": "50m", "memory": "64Mi"}, "limits": {"cpu": "500m", "memory": "256Mi"}},
        "servingMigrateOnStart": serving_value(chart),
    }


def _flow(items):
    return "[" + ", ".join(items) + "]"


def values_block(v):
    q = lambda s: '"' + s + '"' if s == "" or not re.fullmatch(r"[A-Za-z0-9_./-]+", s) or s in ("true", "false") else s
    lines = [
        BEGIN,
        "# Owner-role migration Job (templates/migrate-job.yaml): an Argo CD PreSync hook that runs the image's migrate command",
        "# as the schema owner before the release's pods change; a failed migration fails the sync. Serving pods keep",
        "# MIGRATE_ON_START=false and connect as depot_app. ownerSecret holds the owner role's Postgres URL under ownerSecretKey",
        "# (provisioned with the database). Override per environment in deploy/envs/<env>/values or the Application's values.",
        "migrateJob:",
        f"  enabled: {str(v['enabled']).lower()}",
        f"  command: {_flow(q(c) for c in v['command'])}",
        f"  args: {_flow(q(a) for a in v['args'])}",
        f"  ownerSecret: {q(v['ownerSecret'])}",
        f"  ownerSecretKey: {q(v['ownerSecretKey'])}",
        f"  backoffLimit: {v['backoffLimit']}",
        f"  activeDeadlineSeconds: {v['activeDeadlineSeconds']}",
        "  resources:",
        f"    requests: {{cpu: {v['resources']['requests']['cpu']}, memory: {v['resources']['requests']['memory']}}}",
        f"    limits: {{cpu: {q(v['resources']['limits']['cpu'])}, memory: {v['resources']['limits']['memory']}}}",
        "  # Values path of the serving pods' MIGRATE_ON_START: the Job refuses to render while it is \"true\".",
        f"  servingMigrateOnStart: {q(v['servingMigrateOnStart'])}",
        END,
    ]
    return "\n".join(lines) + "\n"


def with_block(text, block):
    pattern = re.compile(rf"\n*{re.escape(BEGIN)}\n.*?{re.escape(END)}\n", re.S)
    if pattern.search(text):
        return pattern.sub(lambda _: "\n\n" + block, text, count=1)
    i = text.find(INGRESS_BEGIN)
    if i >= 0:
        return text[:i].rstrip("\n") + "\n\n" + block + "\n" + text[i:]
    return text.rstrip("\n") + "\n\n" + block


TEMPLATE = """{{- /* GENERATED by deploy/scripts/gen_migrate_jobs.py, identical in every chart with migrations: edit the script, not this file. */ -}}
{{- $mj := .Values.migrateJob | default dict }}
{{- if $mj.enabled }}
{{- if not $mj.ownerSecret }}{{ fail "migrateJob.ownerSecret must name the Secret with the owner role's database URL (D28)" }}{{ end }}
{{- if not (or $mj.command $mj.args) }}{{ fail "migrateJob.command or migrateJob.args must run the image's migrate command: run deploy/scripts/gen_migrate_jobs.py" }}{{ end }}
{{- with $mj.servingMigrateOnStart }}
{{- $v := $.Values }}
{{- range splitList "." . }}{{ $v = index ($v | default dict) . }}{{ end }}
{{- if eq (toString $v) "true" }}
{{- fail (printf "%s is true while migrateJob.enabled: the serving pods would migrate on start as depot_app as well. Set it to false (the Job applies the migrations as the owner role) or disable the Job (dev only; ADR-0012 rule 3, D28)" .) }}
{{- end }}
{{- end }}
{{- $repo := include "depot.imageRepository" . }}
{{- $image := printf "%s:%s" $repo (.Values.image.tag | default .Chart.AppVersion) }}
{{- if .Values.image.digest }}{{ $image = printf "%s@%s" $repo .Values.image.digest }}{{ end }}
# Owner-role migration Job (ADR-0012 rule 3, D28). Argo CD runs it as a PreSync hook, before any other resource of the
# release is synced, and keeps the last run (and its pod's log) until the next sync replaces it; a failed run fails the sync,
# so pods never roll onto a schema that was not applied. The pod connects as the schema owner (migrateJob.ownerSecret, as
# DATABASE_URL and MIGRATE_DATABASE_URL); serving pods run with MIGRATE_ON_START=false as depot_app. Its labels are not
# the service's: the Service does not route to it and the chart's NetworkPolicy neither selects nor admits it, so the
# namespace default-deny refuses all ingress (it opens no port).
apiVersion: batch/v1
kind: Job
metadata:
  name: {{ .Release.Name }}-migrate
  labels:
    app.kubernetes.io/name: {{ .Chart.Name }}-migrate
    app.kubernetes.io/component: migrate
    app.kubernetes.io/part-of: {{ .Chart.Name }}
  annotations:
    argocd.argoproj.io/hook: PreSync
    argocd.argoproj.io/hook-delete-policy: BeforeHookCreation
    helm.sh/hook: pre-install,pre-upgrade
    helm.sh/hook-delete-policy: before-hook-creation
spec:
  backoffLimit: {{ $mj.backoffLimit | default 2 }}
  activeDeadlineSeconds: {{ $mj.activeDeadlineSeconds | default 600 }}
  template:
    metadata:
      labels:
        app.kubernetes.io/name: {{ .Chart.Name }}-migrate
        app.kubernetes.io/component: migrate
        app.kubernetes.io/part-of: {{ .Chart.Name }}
    spec:
      restartPolicy: Never
      automountServiceAccountToken: false
      securityContext:
        runAsNonRoot: true
        seccompProfile:
          type: RuntimeDefault
      containers:
        - name: migrate
          image: {{ $image | quote }}
          imagePullPolicy: {{ .Values.image.pullPolicy | default "IfNotPresent" }}
          {{- with $mj.command }}
          command: {{ toJson . }}
          {{- end }}
          {{- with $mj.args }}
          args: {{ toJson . }}
          {{- end }}
          securityContext:
            allowPrivilegeEscalation: false
            readOnlyRootFilesystem: true
            capabilities:
              drop: [ALL]
          env:
            {{- with include "depot.cloudEnv" $ | trim }}
            {{- . | nindent 12 }}
            {{- end }}
            - name: DATABASE_URL
              valueFrom:
                secretKeyRef:
                  name: {{ $mj.ownerSecret | quote }}
                  key: {{ $mj.ownerSecretKey | default "DATABASE_URL" | quote }}
            - name: MIGRATE_DATABASE_URL
              valueFrom:
                secretKeyRef:
                  name: {{ $mj.ownerSecret | quote }}
                  key: {{ $mj.ownerSecretKey | default "DATABASE_URL" | quote }}
          resources:
            {{- toYaml $mj.resources | nindent 12 }}
{{- end }}
"""


def outputs():
    files = {}
    for service, chart in charts():
        files[chart / "templates" / TEMPLATE_NAME] = TEMPLATE
        values = chart / "values.yaml"
        files[values] = with_block(values.read_text(), values_block(job_values(service, chart)))
    return files


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="report stale files instead of writing them")
    args = parser.parse_args(argv)
    stale = []
    for path, text in outputs().items():
        current = path.read_text() if path.is_file() else None
        if current == text:
            continue
        stale.append(path)
        if not args.check:
            path.write_text(text)
    if args.check and stale:
        for path in stale:
            print(f"stale: {path.relative_to(REPO)}", file=sys.stderr)
        print("run python3 deploy/scripts/gen_migrate_jobs.py", file=sys.stderr)
        return 1
    if not args.check:
        print(f"wrote {len(stale)} file(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
