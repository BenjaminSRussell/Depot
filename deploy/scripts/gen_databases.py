#!/usr/bin/env python3
"""Generate every service database and its Secrets for an environment (D4, ADR-0012, B-09 part b: stage).

    python3 deploy/scripts/gen_databases.py           # write deploy/envs/stage/databases and deploy/envs/stage/kafka-secrets
    python3 deploy/scripts/gen_databases.py --check   # exit 1 when a committed file differs from the generated one

Needs helm: the Secret each service's serving pods read DATABASE_URL from (its name, key and the other keys they read from
it) and the owner Secret of its migration Job are read from the chart rendered with its stage Application, so a chart
change shows up here (and in --check) instead of in a pod that cannot start.

The topology mirrors dev, so deploy/kafka/connect.yaml's connectors work unchanged: one Postgres per namespace whose
services connect.yaml points at (postgres.<ns>.svc: hello-ledger, metadata, batch), each a StatefulSet with a volume, TLS
from a cert-manager certificate (only `hostssl` lines in pg_hba, so every TCP connection is encrypted and password
authenticated with SCRAM), logical WAL for the outbox connectors. Production topology (replicas, PITR) is B-48.

For each chart with migrations (gen_migrate_jobs.charts()) in the environment:
- a database (connect.yaml's database.dbname for the service's outbox connector, else depot_<service>), owned by the owner
  role <database>_owner, which the chart's migration Job signs in as; PUBLIC loses CONNECT, depot_app (NOBYPASSRLS, the
  serving role, one per Postgres) gets CONNECT and TEMPORARY only, and the migrations grant it the rest (ADR-0012 rule 2);
- the outbox connector's REPLICATION role (the username dev's debezium-cdc-<service> Secret names, which the service's
  migrations grant SELECT on outbox to) with CONNECT on that database;
- an ExternalSecret `<chart>-db-owner` (the Job's DATABASE_URL: the owner role's URL) and one for the serving Secret (the
  key the chart reads DATABASE_URL from, as depot_app's URL, plus the other required keys the serving pods read from that
  Secret, each from Vault <prefix>/<service>/<key>). Both are synced before the service's Application (wave -2), never as
  ordinary resources of it, so the PreSync Job finds its Secret on the first install (D4 rule).
Passwords come from the ClusterSecretStore `depot` (Vault keys <prefix>/<service>-postgres/{owner,cdc}-password and
<prefix>/<namespace>-postgres/{postgres,app}-password; nothing is created by hand). A PostSync Job reconciles the roles,
their passwords and the databases on every sync: CREATE when missing, ALTER ROLE ... PASSWORD always, so rotating a Vault
key and syncing rotates the role. Kafka Connect's copies of the CDC passwords and Apicurio's database Secret are dev's
deploy/envs/dev/kafka-secrets with the stage Vault prefix (deploy/envs/stage/kafka-secrets).
"""

