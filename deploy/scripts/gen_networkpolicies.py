def load_yaml(path):
    return [d for d in yaml.safe_load_all(path.read_text()) if d]


def env_services(env):
    """{release: {"path": chart dir relative to the repo, "namespace": namespace}} for every service chart of env's apps."""
    out = {}
    for path in sorted((ENVS / env / "apps").glob("*.yaml")):
        for doc in load_yaml(path):
            if doc.get("kind") == "ApplicationSet":
                for el in doc["spec"]["generators"][0]["list"]["elements"]:
                    if el.get("path", "").startswith(("services/", "tools/")):
                        out[el["name"]] = {"path": el["path"], "namespace": el["namespace"]}
            elif doc.get("kind") == "Application":
                spec = doc["spec"]
                for src in spec.get("sources") or [spec.get("source")]:
                    p = (src or {}).get("path", "")
                    if p.startswith(("services/", "tools/")) and (REPO / p / "Chart.yaml").is_file():
                        release = (src.get("helm") or {}).get("releaseName", doc["metadata"]["name"])
                        out[release] = {"path": p, "namespace": spec["destination"]["namespace"]}
    return out


def services():
    return env_services("dev")


def templates(chart):
    """The chart's templates, without this script's own and without the migration Job (gen_migrate_jobs.py): the Job's pod
    (app.kubernetes.io/name <chart>-migrate) opens no port and calls no peer, so it is neither selected here, which leaves
    it to the namespace default-deny, nor admitted as a peer by any other chart."""
    skip = {TEMPLATE_NAME, MIGRATE_JOB_TEMPLATE}
    return sorted(p for p in (REPO / chart / "templates").iterdir() if p.is_file() and p.name not in skip)


def pod_names(chart):
    """Every app.kubernetes.io/name value the chart's templates set, resolved without helm."""
    root = REPO / chart
    chart_name = yaml.safe_load((root / "Chart.yaml").read_text())["name"]
    values = yaml.safe_load((root / "values.yaml").read_text()) or {}
    names = set()
    for tpl in templates(chart):
        text = tpl.read_text()
        for raw in NAME_LABEL.findall(text):
            name = raw.replace("{{ .Chart.Name }}", chart_name).replace("{{ $.Chart.Name }}", chart_name)
            if "{{ .Values.serviceName }}" in name:
                name = name.replace("{{ .Values.serviceName }}", values["serviceName"])
            if "{{ $job.command }}" in name:  # hr's per-command CronJobs: include "hr.tenantJob" (dict ... "command" "<x>" ...)
                names |= {name.replace("{{ $job.command }}", c) for c in re.findall(r'"command" "([a-z0-9-]+)"', text)}
                continue
            if "{{" in name or not name:
                raise SystemExit(f"{tpl.relative_to(REPO)}: cannot resolve app.kubernetes.io/name {raw!r}; teach pod_names()")
            names.add(name)
    return sorted(names)


def has_ports(chart):
    return any("containerPort" in t.read_text() for t in templates(chart))


def url_target(stem, releases):
    """The release a URL env-var stem names: the whole stem, or the stem behind one caller prefix; "" for a chartless
    service; None when it names nothing."""
    candidates = [stem] + [stem[len(p):] for p in CALLER_PREFIXES if stem.startswith(p) and len(stem) > len(p)]
    for c in candidates:
        if c in URL_ALIASES:
            return URL_ALIASES[c]
        if c in NO_CHART_URLS:
            return ""
        if c.lower().replace("_", "-") in releases:
            return c.lower().replace("_", "-")
    return None


def url_targets(chart, releases):
    """{target release: [env vars]} for every peer client the chart's templates configure."""
    found = {}
    sources = [(tpl, URL_ENV.findall(tpl.read_text())) for tpl in templates(chart)]
    values = REPO / chart / "values.yaml"
    sources.append((values, value_env_names(yaml.safe_load(values.read_text()))))  # env maps passed through (config, env)
    for tpl, envs in sources:
        for env in envs:
            if env in EXTERNAL_URLS:
                continue
            target = url_target(re.sub(r"(_BASE)?_URL$", "", env), releases)
            if target is None:
                raise SystemExit(f"{tpl.relative_to(REPO)}: {env} names no service chart; add it to EXTERNAL_URLS, URL_ALIASES "
                                 f"or NO_CHART_URLS in deploy/scripts/gen_networkpolicies.py")
            if target:
                found.setdefault(target, set()).add(env)
    return {k: sorted(v) for k, v in found.items()}


def value_env_names(node):
    """The URL env-var names a values tree carries as map keys or as `name:` strings (charts that pass env maps through)."""
    if isinstance(node, dict):
        return [n for k, v in node.items() for n in ([k] if URL_ENV.fullmatch(str(k)) else []) + value_env_names(v)]
    if isinstance(node, list):
        return [n for v in node for n in value_env_names(v)]
    return [node] if isinstance(node, str) and URL_ENV.fullmatch(node) else []


def grant_edges(releases):
    grants = json.loads(GRANTS.read_text())["service_grants"]
    edges = set()
    for caller, targets in grants.items():
        for target in targets:
            c, t = PRINCIPAL_ALIASES.get(caller, caller), PRINCIPAL_ALIASES.get(target, target)
            if c in NO_CHART_PRINCIPALS or t in NO_CHART_PRINCIPALS:
                continue
            for n in (c, t):
                if n not in releases:
                    raise SystemExit(f"{GRANTS.relative_to(REPO)}: service principal {n!r} is no chart release; add it to "
                                     f"PRINCIPAL_ALIASES or NO_CHART_PRINCIPALS in deploy/scripts/gen_networkpolicies.py")
            edges.add((c, t))
    return edges


def routed_gateways(releases):
    """{release: {gateway names}} from the HTTPRoutes in deploy/gateway (the kustomization and payments-webhook)."""
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import gen_httproutes  # the chart Service table the routes are generated from (B-02a)
    table = {key: b.release for key, b in gen_httproutes.service_table().items()}
    out = {}
    for path in sorted(GATEWAY_DIR.rglob("*.yaml")):
        for doc in load_yaml(path):
            if doc.get("kind") != "HTTPRoute":
                continue
            gateways = {p["name"] for p in doc["spec"].get("parentRefs", [])} - set(TOKENLESS_GATEWAYS)
            if not gateways:
                continue
            route_ns = doc["metadata"].get("namespace", GATEWAYS_NAMESPACE)
            for rule in doc["spec"].get("rules", []):
                for ref in rule.get("backendRefs", []):
                    name = table.get((ref.get("namespace", route_ns), ref["name"]))
                    name = name or BACKEND_ALIASES.get(ref["name"], ref["name"])
                    if name not in releases:
                        raise SystemExit(f"{path.relative_to(REPO)}: backendRef {ref['name']!r} is no chart release; add it to BACKEND_ALIASES")
                    out.setdefault(name, set()).update(gateways)
    return out


def metrics_ports(chart):
    root = REPO / chart / "templates"
    sm = root / "servicemonitor.yaml"
    if sm.is_file():
        ports = set(re.findall(r"^\s*-?\s*port:\s*(\w+)", sm.read_text(), re.M))
        return sorted({"admin": ADMIN_PORT, "http": API_PORT}[p] for p in ports)
    has_admin = any(re.search(r"name:\s*admin\b", t.read_text()) for t in templates(chart))
    return [ADMIN_PORT] if has_admin else []


def peer_entry(caller, target, svcs, names):
    entry = {"name": caller}
    if svcs[caller]["namespace"] != svcs[target]["namespace"]:
        entry["namespace"] = svcs[caller]["namespace"]
    entry["podNames"] = names[caller]
    return entry


def model():
    """({release: ingressPolicy values}, {(caller, target): reasons}, services). Reasons name the URL client or the grant;
    a grant without a client is admitted only through GRANT_ONLY_PEERS."""
    svcs = services()
    releases = set(svcs)
    names = {r: pod_names(s["path"]) for r, s in svcs.items()}
    why, admitted = {}, set()
    for caller, s in svcs.items():
        for target, envs in url_targets(s["path"], releases).items():
            why.setdefault((caller, target), []).append("env " + ", ".join(envs))
            admitted.add((caller, target))
    for edge in sorted(grant_edges(releases)):
        if edge in admitted:
            why[edge].append("service grant")
        elif edge in GRANT_ONLY_PEERS:
            why.setdefault(edge, []).append(f"GRANT ONLY, allowlisted: {GRANT_ONLY_PEERS[edge]}")
            admitted.add(edge)
        elif edge in GRANT_WITHOUT_CLIENT:
            why.setdefault(edge, []).append(f"GRANT ONLY, not admitted: {GRANT_WITHOUT_CLIENT[edge]}")
        else:
            raise SystemExit(f"{GRANTS.relative_to(REPO)}: grant {edge[0]} -> {edge[1]} has no *_URL client in the caller's chart; "
                             f"set the URL in the chart if the code calls it, or list the edge in GRANT_ONLY_PEERS or "
                             f"GRANT_WITHOUT_CLIENT in deploy/scripts/gen_networkpolicies.py")
    for edge in list(GRANT_ONLY_PEERS) + list(GRANT_WITHOUT_CLIENT):
        if not any(w.startswith("GRANT ONLY") for w in why.get(edge, [])):
            raise SystemExit(f"stale GRANT_ONLY_PEERS/GRANT_WITHOUT_CLIENT entry {edge}: it is no grant without a client")
    routes = routed_gateways(releases)
    out = {}
    for target, s in sorted(svcs.items()):
        callers = sorted(c for c, t in admitted if t == target)
        gateways = set() if target in GATEWAY_EXEMPT else {DEFAULT_GATEWAY}
        gateways |= routes.get(target, set()) - set(TOKENLESS_GATEWAYS)
        if not has_ports(s["path"]):  # nothing listens: fully closed
            if callers or routes.get(target):
                raise SystemExit(f"{s['path']}: opens no port, yet {callers or routes[target]} would call it")
            gateways = set()
        policy = {
            "enabled": True,
            "podNames": names[target],
            "apiPort": API_PORT,
            "gateway": {"podsNamespace": GATEWAY_PODS_NAMESPACE, "gatewaysNamespace": GATEWAYS_NAMESPACE, "names": sorted(gateways)},
            "peers": [peer_entry(c, target, svcs, names) for c in callers],
            "metricsPorts": metrics_ports(s["path"]) if has_ports(s["path"]) else [],
            "prometheus": PROMETHEUS,
        }
        if (REPO / s["path"] / "templates" / "ingress.yaml").is_file():
            policy["ingressController"] = INGRESS_CONTROLLER
        out[target] = policy
    return out, why, svcs


class Dumper(yaml.SafeDumper):
    def ignore_aliases(self, data):
        return True


def _list(dumper, value):
    flow = all(isinstance(v, (str, int)) for v in value)
    return dumper.represent_sequence("tag:yaml.org,2002:seq", value, flow_style=flow)


def _dict(dumper, value):
    flow = all(isinstance(v, (str, int, bool)) for v in value.values()) and len(value) <= 3
    return dumper.represent_mapping("tag:yaml.org,2002:map", value.items(), flow_style=flow)


Dumper.add_representer(list, _list)
Dumper.add_representer(dict, _dict)


def values_block(policy):
    body = yaml.dump({"ingressPolicy": policy}, Dumper=Dumper, sort_keys=False, width=120, default_flow_style=False)
    note = ("# Default-deny ingress (templates/networkpolicy-ingress.yaml): only these Gateways' Envoy pods and these peer\n"
            "# services reach the API port, only Prometheus the metrics port. Override per environment in deploy/envs/<env>/values;\n"
            "# regenerate after changing the grant table (policies/authz/data.json), a chart's *_URL clients or an HTTPRoute.\n")
    return f"{BEGIN}\n{note}{body}{END}\n"


def with_block(text, block):
    pattern = re.compile(rf"\n*{re.escape(BEGIN)}\n.*?{re.escape(END)}\n", re.S)
    if pattern.search(text):
        return pattern.sub(lambda _: "\n\n" + block, text, count=1)
    return text.rstrip("\n") + "\n\n" + block


