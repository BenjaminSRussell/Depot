def outputs():
    policies, _, svcs = model()
    files = {}
    for release, policy in policies.items():
        chart = REPO / svcs[release]["path"]
        files[chart / "templates" / TEMPLATE_NAME] = TEMPLATE
        values = chart / "values.yaml"
        files[values] = with_block(values.read_text(), values_block(policy))
    files[DEFAULT_DENY] = DEFAULT_DENY_POLICY
    for env in ENV_DESTINATIONS:
        files[ENVS / env / "apps" / DEFAULT_DENY_APPSET] = default_deny_appset(env)
    return files


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="report stale files instead of writing them")
    parser.add_argument("--explain", action="store_true", help="print each service's gateways and peers with their sources")
    args = parser.parse_args(argv)
    if args.explain:
        policies, why, _ = model()
        for target, p in policies.items():
            print(f"{target}: gateways {p['gateway']['names']}, metrics {p['metricsPorts']}")
            for peer in p["peers"]:
                print(f"    <- {peer['name']}: {'; '.join(why[(peer['name'], target)])}")
            for (caller, t), reasons in sorted(why.items()):
                if t == target and caller not in [peer["name"] for peer in p["peers"]]:
                    print(f"    x- {caller}: {'; '.join(reasons)}")
        return 0
    stale = []
    for path, text in outputs().items():
        current = path.read_text() if path.is_file() else None
        if current == text:
            continue
        stale.append(path)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if args.check and stale:
        for path in stale:
            print(f"stale: {path.relative_to(REPO)}", file=sys.stderr)
        print("run python3 deploy/scripts/gen_networkpolicies.py", file=sys.stderr)
        return 1
    if not args.check:
        print(f"wrote {len(stale)} file(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
